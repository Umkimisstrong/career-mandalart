export type Sub = { id: string; label: string; ages?: AgeBand[]; kw?: string[]; acts: Act[] };

type Opt = { ages?: AgeBand[]; kw?: string[] };
const sub = (id: string, label: string, opt: Opt, acts: string[]): Sub => ({
  id, label, ...opt,
  acts: acts.map(a => {
    const [l, unit] = a.split('/');
    return unit ? { label: l, unit } : { label: l };
  }),
});

