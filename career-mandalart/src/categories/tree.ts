export const subsOf = (catId?: string) => (catId ? SUBS[catId] ?? [] : []);
export const subById = (catId?: string, subId?: string) => subsOf(catId).find(s => s.id === subId);

// 연령대가 맞는 영역 → 사람들이 많이 쓴 말(kw)이 있는 영역 → 원래 순서
export function rankSubs(catId?: string, age?: AgeBand): Sub[] {
  const score = (s: Sub) => (age && s.ages?.includes(age) ? 2 : 0) + (s.kw?.length ? 1 : 0);
  return subsOf(catId).map((s, i) => ({ s, i })).sort((a, b) => score(b.s) - score(a.s) || a.i - b.i).map(x => x.s);
}

// 바깥 블록의 실행 과제 칸(가운데 제외 8칸)마다 기본으로 안내할 세부 카테고리
export function guideSub(catId: string | undefined, cell: number, age?: AgeBand): Sub | undefined {
  const ranked = rankSubs(catId, age);
  if (!ranked.length) return undefined;
  const slot = cell < 4 ? cell : cell - 1;
  return ranked[slot % ranked.length];
}
